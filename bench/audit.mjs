// Independent audit of Revenge42.
//
//  A. Verify solutions with cubing.js, which shares no code with the solver.
//  B. Audit the move metric token by token.
//  C. Census min2phase's return codes to see whether any reduction ever
//     hands it an illegal 3x3x3 state, which is what a parity bug would do.
//
//   node audit.mjs [trials] [budgetMs]

import { puzzles } from "cubing/puzzles";
import { createRequire } from "module";

const require = createRequire(import.meta.url);
const { createEngine } = require("../src/engine.js");

const TRIALS = Number(process.argv[2] || 150);
const BUDGET = Number(process.argv[3] || 3000);

const kpuzzle = await puzzles["4x4x4"].kpuzzle();
const solved = kpuzzle.defaultPattern();

// The 24 solved-but-rotated patterns, generated by closure under x and y
// rather than by a hand-written list, which is easy to get wrong.
const rotatedSolved = [];
{
  const seen = new Set();
  const queue = [solved];
  while (queue.length) {
    const p = queue.shift();
    const key = JSON.stringify(p.patternData);
    if (seen.has(key)) continue;
    seen.add(key);
    rotatedSolved.push(p);
    for (const g of ["x", "y"]) queue.push(p.applyAlg(g));
  }
  console.log("solved-orientation class size: %d (expected 24)\n", rotatedSolved.length);
}
const isSolvedAnyOrientation = (p) => rotatedSolved.some((q) => p.isIdentical(q));

const engine = createEngine();
const S = engine.scramble_444;
S.init();
S.setConfig({ phase2Sols: 300 });

// --- C. instrument min2phase before any solving happens ------------------
const origSolution = engine.min2phase.Search.prototype.solution;
const codes = Object.create(null);
engine.min2phase.Search.prototype.solution = function (...args) {
  const r = origSolution.apply(this, args);
  if (typeof r === "string" && r.startsWith("Error")) {
    codes[r] = (codes[r] || 0) + 1;
  } else {
    codes.ok = (codes.ok || 0) + 1;
  }
  return r;
};

// --- move metric vocabulary ----------------------------------------------
const FACES = ["U", "R", "F", "D", "L", "B"];
const VOCAB = new Set();
for (const f of FACES) for (const w of ["", "w"]) for (const a of ["", "2", "'"]) VOCAB.add(f + w + a);

const parse = (tok) => {
  const m = /^([URFDLB])(w?)([2']?)$/.exec(tok);
  if (!m) return null;
  return { face: m[1], wide: m[2] === "w", amount: m[3] === "2" ? 2 : 1 };
};

let identical = 0;
let solvedUpToRotation = 0;
let broken = 0;
const brokenExamples = [];

let countMismatch = 0, reportedTotal = 0, emittedTotal = 0;
const mismatchExamples = [];
let obtm = 0, qtm = 0, sstm = 0, sqtm = 0;
let wideTokens = 0, halfTokens = 0, sliceTokens = 0, badTokens = 0;
let adjacentSameAxisPairs = 0, adjacentSameFaceSameWidth = 0;

console.log("Running %d solves at %d ms…\n", TRIALS, BUDGET);

for (let i = 0; i < TRIALS; i++) {
  const scramble = S.getRandomScramble().trim();
  const state = S.scrambleToState(scramble);
  const res = S.solve(state, { budgetMs: BUDGET });
  if (res.error) { broken++; brokenExamples.push("solver error: " + res.error); continue; }

  // --- A. independent verification --------------------------------------
  let pattern;
  try {
    pattern = solved.applyAlg(scramble).applyAlg(res.solution);
  } catch (e) {
    broken++; brokenExamples.push("cubing.js rejected an alg: " + e.message); continue;
  }
  if (pattern.isIdentical(solved)) {
    identical++;
  } else {
    // Solved but left in a rotated orientation is still a valid solve.
    if (isSolvedAnyOrientation(pattern)) solvedUpToRotation++;
    else { broken++; brokenExamples.push({ scramble, solution: res.solution }); }
  }

  // --- B. metric audit ---------------------------------------------------
  const toks = res.solution.trim().split(/\s+/);

  // The reported figure must be the length of the sequence that was just
  // verified. If a parity fix were appended outside the count, or counted
  // but not emitted, these two would diverge.
  if (toks.length !== res.moves) {
    countMismatch++;
    if (mismatchExamples.length < 3) {
      mismatchExamples.push({ reported: res.moves, emitted: toks.length, solution: res.solution });
    }
  }
  reportedTotal += res.moves;
  emittedTotal += toks.length;
  let prev = null;
  for (const tok of toks) {
    if (!VOCAB.has(tok)) { badTokens++; if (/^\d|^[a-z]|^[MES]/.test(tok)) sliceTokens++; continue; }
    const p = parse(tok);
    if (p.wide) wideTokens++;
    if (p.amount === 2) halfTokens++;

    obtm += 1;                              // wide 1, half 1
    qtm += p.amount;                        // half turn costs 2
    sstm += p.wide ? 2 : 1;                 // wide is two single slices
    sqtm += (p.wide ? 2 : 1) * p.amount;

    if (prev) {
      const sameAxis = { U: "UD", D: "UD", R: "RL", L: "RL", F: "FB", B: "FB" };
      if (sameAxis[prev.face] === sameAxis[p.face]) adjacentSameAxisPairs++;
      if (prev.face === p.face && prev.wide === p.wide) adjacentSameFaceSameWidth++;
    }
    prev = p;
  }

  if ((i + 1) % 25 === 0) process.stdout.write(`  ${i + 1}/${TRIALS}\n`);
}

const done = identical + solvedUpToRotation;
console.log("\n=== A. Independent verification (cubing.js) ===");
console.log("  exactly solved              : %d", identical);
console.log("  solved but rotated          : %d", solvedUpToRotation);
console.log("  NOT SOLVED                  : %d", broken);
if (brokenExamples.length) console.log("  first failure:", JSON.stringify(brokenExamples[0]).slice(0, 400));

console.log("\n=== B. Move metric ===");
console.log("  reported count != emitted tokens : %d  (must be 0)", countMismatch);
if (mismatchExamples.length) console.log("  example:", JSON.stringify(mismatchExamples[0]));
console.log("  total reported %d vs total emitted %d", reportedTotal, emittedTotal);
console.log("  tokens outside the 36-move set   : %d (slice-notation tokens: %d)", badTokens, sliceTokens);
console.log("  wide (double-layer) tokens       : %d", wideTokens);
console.log("  half-turn tokens                 : %d", halfTokens);
console.log("  adjacent same-face same-width    : %d  (should be 0; would mean merging failed)", adjacentSameFaceSameWidth);
console.log("  adjacent same-axis pairs         : %d  (legitimate, e.g. Rw then R')", adjacentSameAxisPairs);
console.log("  average per solve:");
console.log("    OBTM  wide=1 half=1 : %s   <-- the metric reported everywhere", (obtm / done).toFixed(2));
console.log("    QTM   wide=1 half=2 : %s", (qtm / done).toFixed(2));
console.log("    SSTM  wide=2 half=1 : %s", (sstm / done).toFixed(2));
console.log("    SQTM  wide=2 half=2 : %s", (sqtm / done).toFixed(2));

console.log("\n=== C. min2phase return codes ===");
for (const k of Object.keys(codes).sort()) console.log("  %s: %d", k, codes[k]);
console.log("  Errors 1-6 mean an ILLEGAL 3x3x3 state was handed to it.");
console.log("  Errors 7-8 mean it simply found nothing within the depth or probe limit.");
